"""Generate `crates/swadesh-cli/src/datasets.rs` from sacreBLEU's own dataset registry.

The catalogue (names, descriptions, download URLs, md5s, language pairs and citations) is
sacreBLEU's data, Apache-2.0; this records it as Rust constants so the standalone binary can list
and fetch test sets without sacreBLEU.

The **field names per language pair** are measured from the oracle's own `-t NAME --list` output
rather than from its object model: that is the documented black-box surface, it is the order
sacreBLEU prints (`src, ref:B, ref:C, docid, origlang, <systems>, domain`) which `--echo all` and
the "available fields" error line reproduce, and it is therefore what the CLI must match. The
registry's flat URL list is not per-field: one archive serves several fields, which is why the
fields are not reconstructed from it.

Run with the interpreter that has sacrebleu 2.6.0 installed:

    ~/venv311/bin/python tools/gen_datasets.py
"""

import io
import subprocess
import sys

import sacrebleu
import sacrebleu.dataset as dataset

OUT = "crates/swadesh-cli/src/datasets.rs"


def rust_str(s: str) -> str:
    """A Rust string literal: raw when that is simplest, escaped otherwise."""
    if '"#' not in s and "\r" not in s:
        return 'r#"%s"#' % s
    return '"%s"' % s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "\\r")


def listed_fields(name: str) -> "list[tuple[str, list[str]]]":
    """`[(langpair, [field, ...]), ...]` from the oracle's `-t NAME --list`."""
    out = subprocess.run(
        [sys.executable, "-m", "sacrebleu", "-t", name, "--list"],
        capture_output=True, text=True, check=True,
    )
    rows = []
    for line in out.stdout.splitlines():
        if ": " not in line:
            continue
        pair, rest = line.split(": ", 1)
        fields = [f.strip() for f in rest.split(",") if f.strip()]
        rows.append((pair.strip(), fields))
    if not rows:
        raise SystemExit(f"no fields listed for {name!r}")
    return rows


def main() -> int:
    entries = sorted(dataset.DATASETS.items())
    lines = [
        "//! The test-set catalogue, generated by `tools/gen_datasets.py` from sacreBLEU's own",
        "//! dataset registry (Apache-2.0, Copyright Matt Post and contributors). Do not edit by hand.",
        "//!",
        "//! This file is data, not code: it holds what `--list` prints, the field names each language",
        "//! pair offers (measured from the oracle's `-t NAME --list`), and what a download would need",
        "//! (URLs, md5s, language pairs and citations). Regenerate it when sacreBLEU's catalogue",
        "//! changes, and update the record in `NOTICE`.",
        "",
        "/// One test set, as sacreBLEU describes it.",
        "pub struct Dataset {",
        "    pub name: &'static str,",
        "    pub description: &'static str,",
        "    pub citation: Option<&'static str>,",
        "    pub data: &'static [&'static str],",
        "    pub md5: &'static [&'static str],",
        "    pub langpairs: &'static [&'static str],",
        "    /// `fields[i]` are the fields of `langpairs[i]`, in sacreBLEU's own order.",
        "    pub fields: &'static [&'static [&'static str]],",
        "    /// `paths[i]` are the archive-relative files of `langpairs[i]`, from the registry's\n",
        "    /// own `langpairs` mapping (a pair whose entry is a dict contributes its `path`): the\n",
        "    /// plain-text parser copies them and the other families locate their input with them.",
        "    pub paths: &'static [&'static [&'static str]],",
        "}",
        "",
        "/// Every test set, in the order sacreBLEU's `--list` prints them.",
        "pub const DATASETS: &[Dataset] = &[",
    ]
    for name, ds in entries:
        desc = getattr(ds, "description", None) or ""
        cite = getattr(ds, "citation", None)
        data = list(getattr(ds, "data", None) or [])
        md5 = list(getattr(ds, "md5", None) or [])
        pairs = list((getattr(ds, "langpairs", None) or {}).keys())
        listed = listed_fields(name)
        if [p for p, _ in listed] != pairs:
            raise SystemExit(
                f"{name}: the oracle lists {[p for p, _ in listed]} but the registry declares {pairs}"
            )
        lines.append("    Dataset {")
        lines.append("        name: %s," % rust_str(name))
        lines.append("        description: %s," % rust_str(desc))
        lines.append(
            "        citation: %s," % ("None" if cite is None else "Some(%s)" % rust_str(cite))
        )
        lines.append("        data: &[%s]," % ", ".join(rust_str(u) for u in data))
        lines.append("        md5: &[%s]," % ", ".join(rust_str(m) for m in md5))
        lines.append("        langpairs: &[%s]," % ", ".join(rust_str(p) for p in pairs))
        lines.append(
            "        fields: &[%s],"
            % ", ".join("&[%s]" % ", ".join(rust_str(f) for f in fs) for _, fs in listed)
        )
        raw_pairs = getattr(ds, "langpairs", None) or {}
        per_pair = []
        for key in pairs:
            entry = raw_pairs.get(key)
            if isinstance(entry, dict):
                entry = [entry["path"]] if "path" in entry else []
            elif isinstance(entry, str):
                entry = [entry]
            per_pair.append(list(entry or []))
        lines.append(
            "        paths: &[%s],"
            % ", ".join("&[%s]" % ", ".join(rust_str(str(p)) for p in paths) for paths in per_pair)
        )
        lines.append("    },")
    lines.append("];")
    lines.append("")
    io.open(OUT, "w", encoding="utf-8").write("\n".join(lines))
    print(f"wrote {OUT}: {len(entries)} test sets, for sacrebleu {sacrebleu.__version__}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
