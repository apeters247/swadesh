"""Generate exact Unicode property tables from the *installed* Python + `regex`,
so Rust tokenizers behave bit-identically to sacrebleu on this interpreter.

Usage: python tools/gen_tables.py > crates/swadesh-core/src/tables.rs
"""
import sys
import regex

def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            ok = False
        else:
            ok = pred(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1)); start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out

N = regex.compile(r'\p{N}'); P = regex.compile(r'\p{P}'); S = regex.compile(r'\p{S}')
tables = {
    'PY_WHITESPACE': ranges(lambda c: c.isspace() and len(('a' + c + 'b').split()) == 2),
    'REGEX_N': ranges(lambda c: N.match(c) is not None),
    'REGEX_P': ranges(lambda c: P.match(c) is not None),
    'REGEX_S': ranges(lambda c: S.match(c) is not None),
}
print(f"// @generated by tools/gen_tables.py on Python {sys.version.split()[0]}, regex {regex.__version__}")
print("// Do not edit by hand.")
print(f'pub const GENERATED_PYTHON: &str = "{sys.version.split()[0]}";')
print(f'pub const GENERATED_REGEX: &str = "{regex.__version__}";')
for name, rs in tables.items():
    print(f"pub static {name}: [(u32, u32); {len(rs)}] = [")
    for a, b in rs:
        print(f"    (0x{a:X}, 0x{b:X}),")
    print("];")
